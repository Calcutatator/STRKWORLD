// Bundles the compiled ReceiptLedger into ledger-artifact.js for the deploy page.
//
//   cd contracts/receipt-ledger && scarb --release build && cd ../..
//   node contracts/receipt-ledger/deploy/build-artifact.mjs           # write
//   node contracts/receipt-ledger/deploy/build-artifact.mjs --check   # fail if stale
//
// It computes the Sierra class hash, the CASM compiled class hash (Blake2s, which
// Starknet requires for new declarations from v0.14.1; mainnet is v0.14.3), and the
// contract's address. The address is fixed in advance because the deploy goes through
// the UDC with `not_from_zero = false`, so it depends only on the class, the salt and
// the constructor arguments, never on who deploys. No keys, no network.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { hash, shortString } from 'starknet';

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, '..', 'target', 'release');
const sierra = JSON.parse(
  readFileSync(join(target, 'receipt_ledger_ReceiptLedger.contract_class.json'), 'utf8'),
);
const casm = JSON.parse(
  readFileSync(join(target, 'receipt_ledger_ReceiptLedger.compiled_contract_class.json'), 'utf8'),
);

// Mainnet constructor arguments, read over RPC on 2026-10-02 (block ~15,783,400):
// the anonymizer's get_privacy_contract() returns this pool, and the pool's
// get_fee_amount() returns 6 STRK.
const ANONYMIZER = '0x04f33230dc57855c6e7eabe66dfa0fde82c5458fd0e54827cdb7cb4c474888a7';
const POOL = '0x040337b1af3c663e86e333bab5a4b28da8d4652a15a69beee2b677776ffe812a';
// OpenZeppelin UDC v2 on mainnet (starknet.js 10.8.0 `constants.UDC`), entry point deploy_contract.
const UDC = '0x02ceed65a4bd731034c01113685c831b01c15d7d432f71afb1cf1634b53a2125';
const SALT = shortString.encodeShortString('strkworld-lb-ledger-v1');

const classHash = hash.computeContractClassHash(sierra);
const compiledClassHash = hash.computeCompiledClassHashBlake(casm);
const constructorCalldata = [ANONYMIZER, POOL];
const address = hash.calculateContractAddressFromHash(SALT, classHash, constructorCalldata, 0);

const artifact = {
  network: 'SN_MAIN',
  chainId: '0x534e5f4d41494e',
  classHash,
  compiledClassHash,
  salt: SALT,
  udc: UDC,
  udcEntryPoint: 'deploy_contract',
  constructorCalldata,
  expectedAddress: address,
  // Selectors of the views the page reads back after deploying.
  selectors: {
    anonymizer: hash.getSelectorFromName('anonymizer'),
    pool: hash.getSelectorFromName('pool'),
  },
  // The shape `wallet_addDeclareTransaction` takes: the ABI as a string, no debug info.
  contractClass: {
    sierra_program: sierra.sierra_program,
    contract_class_version: sierra.contract_class_version,
    entry_points_by_type: sierra.entry_points_by_type,
    abi: JSON.stringify(sierra.abi),
  },
};

const out = join(here, 'ledger-artifact.js');
const body =
  '// Generated by build-artifact.mjs from contracts/receipt-ledger. Do not edit.\n' +
  `window.LEDGER_ARTIFACT = ${JSON.stringify(artifact, null, 1)};\n`;

if (process.argv.includes('--check')) {
  const current = readFileSync(out, 'utf8');
  if (current !== body) {
    console.error('ledger-artifact.js is stale: rebuild it with build-artifact.mjs');
    process.exit(1);
  }
  console.log(`ledger-artifact.js is current (class ${classHash})`);
} else {
  writeFileSync(out, body);
  console.log(`class hash          ${classHash}`);
  console.log(`compiled class hash ${compiledClassHash}`);
  console.log(`contract address    ${address}`);
}
